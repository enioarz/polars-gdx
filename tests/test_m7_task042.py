@pytest.mark.skipif(Reader is None, reason="legacy backend not compiled")
@pytest.mark.parametrize("path", [GDX, M7])
def test_differential_scan_parity(path):
    """Every symbol of both fixtures reads identically through both
    backends, modulo the documented UNDEF/NA/acronym projection
    difference (null vs NaN/7e301) which is normalized explicitly."""
    symbols = [
        r["name"]
        for r in list_symbols(path, backend="legacy").to_dicts()
    ]
    for symbol in symbols:
        legacy = read_gdx(path, symbol=symbol, backend="legacy")
        gdxrs = read_gdx(path, symbol=symbol, backend="gdxrs")
        assert legacy.columns == gdxrs.columns
        assert legacy.height == gdxrs.height, symbol
        assert legacy.schema == gdxrs.schema, symbol
        for column in legacy.columns:
            if legacy.schema[column] == pl.Float64:
                left = legacy[column].to_list()
                right = gdxrs[column].to_list()
                assert len(left) == len(right)
                for a, b in zip(left, right):
                    if a is None or b is None:
                        # null (gdxrs) vs NaN or the native acronym number
                        # (legacy) is the documented projection difference
                        # for UNDEF/NA/acronyms.
                        other = b if a is None else a
                        assert other is None or math.isnan(other) or abs(other) >= 1.0e300
                    elif math.isnan(a) or math.isnan(b):
                        assert math.isnan(a) and math.isnan(b)
                    else:
                        assert a == b or math.isclose(a, b, rel_tol=1e-12), (symbol, column, a, b)
            else:
                assert legacy[column].to_list() == gdxrs[column].to_list(), symbol


