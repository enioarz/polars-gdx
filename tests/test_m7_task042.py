@pytest.mark.parametrize("backend", BACKENDS)
def test_symbol_kinds_and_metadata(backend):
    """Frozen: symbol kinds, dims, record counts, domains and alias target."""
    df = list_symbols(M7, backend=backend)
    by_name = {r["name"]: r for r in df.to_dicts()}
    assert set(by_name) == {"I", "J", "D", "P", "C", "S", "Z", "V", "Q"}
    assert by_name["I"]["type"] == "Set"
    assert by_name["J"]["type"] == "Alias"
    assert by_name["D"]["type"] == "Parameter"
    assert by_name["P"]["type"] == "Parameter"
    assert by_name["V"]["type"] == "Variable"
    assert by_name["Q"]["type"] == "Equation"
    assert [by_name[n]["dim"] for n in ("I", "J", "D", "P", "C")] == [1, 1, 1, 1, 1]
    assert by_name["S"]["dim"] == 0 and by_name["Z"]["dim"] == 0
    assert by_name["I"]["records"] == 2
    assert by_name["P"]["records"] == 7
    assert by_name["C"]["records"] == 2
    assert by_name["D"]["records"] == 0
    # D's strict domain is the alias J itself, not the target set I.
    assert by_name["D"]["domains"] == ["J"]
    # The alias keeps its own identity; its records read like the target's.
    assert by_name["J"]["records"] == 0


