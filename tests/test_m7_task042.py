@pytest.mark.skipif(Reader is None, reason="legacy backend not compiled")
def test_legacy_typed_value_projection_differs_explicitly():
    """Frozen legacy Float64 projection of P: EPS -> +0.0, UNDEF/NA -> NaN
    (not null), +/-INF -> +/-inf, 1.25 exact, acronym 7 -> the native
    encoded acronym number 7 x 10e300. The gdxrs nulls and the legacy NaNs
    are compared as the documented difference, never as equal values."""
    df = read_gdx(M7, symbol="P", backend="legacy")
    values = df["value"].to_list()
    assert values[0] == 0.0
    assert math.isnan(values[1]) and math.isnan(values[2])
    assert values[3] == math.inf and values[4] == -math.inf
    assert values[5] == 1.25
    assert values[6] == pytest.approx(7.0 * 10.0e300)
    # The deliberate difference: gdxrs null where legacy projects NaN/number.
    gdxrs_values = read_gdx(M7, symbol="P", backend="gdxrs")["value"].to_list()
    assert gdxrs_values[1] is None and gdxrs_values[2] is None
    assert gdxrs_values[6] is None


