def test_gdxrs_reader_lifecycle():
    """The gdxrs reader mirrors the legacy Reader lifecycle contract."""
    if GdxrsReader is None:
        pytest.skip("gdxrs backend not compiled")
    reader = GdxrsReader(M7)
    assert reader.uel_table() == UEL_TABLE
    reader.close()
    with pytest.raises(RuntimeError, match="reader is closed"):
        reader.uel_table()
    with pytest.raises(RuntimeError, match="reader is closed"):
        reader.symbols()
    with GdxrsReader(M7) as reader:
        assert len(reader.symbols()) == 9
    with pytest.raises(RuntimeError, match="reader is closed"):
        reader.domain_elements("I", 0)


def test_gdxrs_resolve_uel_indices_used():
    if GdxrsReader is None:
        pytest.skip("gdxrs backend not compiled")
    with GdxrsReader(M7) as reader:
        # Labels resolve to original 1-based UEL IDs.
        assert reader.resolve_uel_indices_used([(0, ["cc", "aa"])], "I") == [(0, [1, 3])]
        # 'seattle' exists globally but is unused in dimension 0 of C:
        # the resolved set is restricted to used UELs and drops to empty.
        assert reader.resolve_uel_indices_used([(0, ["seattle"])], "C") == [(0, [])]
        # Unknown labels resolve to nothing.
        assert reader.resolve_uel_indices_used([(0, ["nope"])], "I") == [(0, [])]
