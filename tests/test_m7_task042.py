@pytest.mark.parametrize("backend", BACKENDS)
def test_case_sensitive_labels(backend):
    """Frozen: `aa` and `AA` are distinct labels; matching is byte-exact."""
    df = read_gdx(M7, symbol="C", key_filter={0: ["aa"]}, backend=backend)
    assert [(r["dim_0"], r["value"]) for r in df.to_dicts()] == [("aa", 10.0)]
    df = read_gdx(M7, symbol="C", key_filter={0: ["AA"]}, backend=backend)
    assert [(r["dim_0"], r["value"]) for r in df.to_dicts()] == [("AA", 20.0)]
    # Wrong case never matches.
    df = read_gdx(M7, symbol="C", key_filter={0: ["Aa"]}, backend=backend)
    assert df.height == 0
    # Predicates match exactly too.
    df = scan_gdx(M7, symbol="C", backend=backend)
    assert df.filter(pl.col("dim_0") == "aa").collect().height == 1
    assert df.filter(pl.col("dim_0") == "AA").collect().height == 1
    assert df.filter(pl.col("dim_0") == "aA").collect().height == 0


